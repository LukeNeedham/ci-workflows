#!/usr/bin/env python3
"""Writes the README.md of the app's screenshot package from docs/screenshot-readme-template.md, so that it explains
the package the same way in every app and cannot drift from the docs.

    python3 screenshot_package_readme.py [app_dir]

Prints `path=<README.md, relative to the app>` to $GITHUB_OUTPUT (or to the screen) when it wrote the file, and
nothing when the app has no screenshot package. The `screenshots` action commits it with the screenshots.
"""

import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "screenshots"))
from conventions.screenshots import package_dir

TEMPLATE = Path(__file__).resolve().parent.parent / "docs" / "screenshot-readme-template.md"
HEADER = ("<!-- Generated by LukeNeedham/ci-workflows from docs/screenshot-readme-template.md: CI keeps it up to date, "
          "do not edit it here. -->\n\n")


def write(app_dir):
    """Writes the README of the package of [app_dir] and returns its path relative to it, or None without a package."""
    app_dir = Path(app_dir)
    folder = package_dir(app_dir)
    if folder is None:
        return None
    readme = folder / "README.md"
    text = HEADER + TEMPLATE.read_text()
    if not readme.is_file() or readme.read_text() != text:
        readme.write_text(text)
    return readme.relative_to(app_dir).as_posix()


def main():
    path = write(sys.argv[1] if len(sys.argv) > 1 else ".")
    if path is None:
        return
    line = f"path={path}"
    if os.environ.get("GITHUB_OUTPUT"):
        with open(os.environ["GITHUB_OUTPUT"], "a") as f:
            f.write(line + "\n")
    else:
        print(line)


if __name__ == "__main__":
    main()
