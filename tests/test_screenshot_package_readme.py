import tempfile
import unittest
from pathlib import Path

import _paths  # noqa: F401
import screenshot_package_readme as p

TEMPLATE = Path(__file__).resolve().parent.parent / "docs" / "screenshot-readme-template.md"


class ScreenshotPackageReadmeTest(unittest.TestCase):
    def app(self, with_package=True):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        app = Path(tmp.name)
        if with_package:
            folder = app / "app" / "src" / "debug" / "kotlin" / "x" / "screenshot"
            folder.mkdir(parents=True)
            (folder / "HomePage.kt").write_text("package x.screenshot\n")
        return app

    def test_the_readme_of_the_package_is_the_template_with_a_generated_header(self):
        app = self.app()
        path = p.write(app)
        self.assertEqual("app/src/debug/kotlin/x/screenshot/README.md", path)
        text = (app / path).read_text()
        self.assertTrue(text.startswith("<!-- Generated by LukeNeedham/ci-workflows"))
        self.assertTrue(text.endswith(TEMPLATE.read_text()))

    def test_a_hand_written_or_old_readme_is_replaced_and_a_current_one_is_left_alone(self):
        app = self.app()
        readme = app / p.write(app)
        readme.write_text("old")
        p.write(app)
        self.assertEqual(p.HEADER + TEMPLATE.read_text(), readme.read_text())
        before = readme.stat().st_mtime_ns
        p.write(app)
        self.assertEqual(before, readme.stat().st_mtime_ns)

    def test_an_app_without_a_package_gets_none(self):
        self.assertIsNone(p.write(self.app(with_package=False)))

    def test_the_template_is_generic_and_names_no_file_of_an_app(self):
        text = TEMPLATE.read_text()
        self.assertIn("order.txt", text)
        self.assertNotIn("see `HomePage.kt`", text)


if __name__ == "__main__":
    unittest.main()
